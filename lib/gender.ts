// Род глагола для отзывов: было «переехал(а)» — машинный артефакт, который сразу
// выдаёт шаблон и роняет доверие (E-E-A-T). Определяем род по имени автора, не
// добавляя поле в данные по всем городам.
//
// Эвристика: русские женские имена почти всегда оканчиваются на -а/-я
// (Мария, Анна, Ольга), мужские — на согласный (Алексей, Дмитрий). Исключения —
// мужские имена на -а/-я (Никита, Илья и т.п.) — держим явным списком.
const MALE_EXCEPTIONS = new Set([
  "Никита", "Илья", "Лука", "Кузьма", "Фома", "Савва", "Данила", "Гаврила",
  "Юра", "Лёва", "Лева", "Добрыня", "Аникита", "Иона", "Фока", "Ероша",
]);

export function movedVerbRu(author: string): "переехал" | "переехала" {
  const first = (author ?? "").trim().split(/\s+/)[0];
  if (!first) return "переехал";
  if (MALE_EXCEPTIONS.has(first)) return "переехал";
  return /[ая]$/i.test(first) ? "переехала" : "переехал";
}
