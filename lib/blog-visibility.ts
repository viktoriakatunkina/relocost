// Единая точка правды: какие статьи blog_posts НЕ показываем в журнале и
// не кладём в sitemap.
//
// Раньше строка "города" была продублирована в четырёх местах (app/sitemap.ts,
// app/[locale]/blog/[slug]/page.tsx, lib/blog.ts ×2) — легко разъезжается.
//
// ⚠️ РЕГИСТР ЗДЕСЬ ЗНАЧИМ И ЭТО НЕ ОПЕЧАТКА.
// «города» (строчная) и «Города» (прописная) — РАЗНЫЙ контент, а не дубль:
//   • «города»  ~1609 опубликованных — справочные DN-карточки городов
//     («Танзания Морогоро DN 2026: 400-680 USD/мес; …»). Это сырьё для
//     блоков CityArticles, а не материалы журнала: скрываем.
//   • «Города»  ~113 опубликованных — нормальные статьи журнала
//     («Стоимость жизни в Рио-де-Жанейро 2026: реальные цифры», «Лучшие
//     районы Праги для жизни эмигрантов»). Их надо показывать и
//     индексировать; именно так их создают seed-скрипты
//     (scripts/seed-10-night-batch9-aug-2026.mjs: tag: "Города").
// Поэтому фильтр обязан быть РЕГИСТРОЗАВИСИМЫМ (neq/eq, а не ilike). Замена
// на регистронезависимое сравнение выкинет 113 хороших статей из индекса —
// проверено на данных 2026-09-07, см. scripts/normalize-blog-tags.mjs.
export const HIDDEN_BLOG_TAG = "города";

/** Кусок query-строки PostgREST для raw fetch: исключает скрытый тег. */
export const BLOG_TAG_FILTER = `tag=neq.${encodeURIComponent(HIDDEN_BLOG_TAG)}`;
