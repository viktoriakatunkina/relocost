// Постраничный архив блога (/blog/page/N).
//
// Зачем он есть: на /blog список статей листает клиентский BlogFilters, из-за
// чего в HTML попадают только 12 карточек текущей страницы. Краулер видит 12
// ссылок и физически не может дойти до остальных ~2600 статей — они
// присутствуют только в сайтмапе, без единой внутренней ссылки. Архив даёт
// серверные <a> на каждую страницу списка (аудит 2026-09-07).
export const ARCHIVE_PAGE_SIZE = 24;

/** Сколько страниц архива при заданном количестве статей. */
export function archivePageCount(total: number): number {
  return Math.max(1, Math.ceil(total / ARCHIVE_PAGE_SIZE));
}
