  pros?: string[]; // сильные стороны направления (3-4)
  cons?: string[]; // что учитывать (3-4)
  // Этап 3 — контекст к цифрам бюджета. Рендерится ВНУТРИ блока «Сколько
  // стоит жить в <стране>» под автотекстом, который собирается из чисел
  // (lib/country-cost-text). Автотекст на всех странах устроен одинаково, и
  // без ручного абзаца страницы стран получались бы шаблонными: cost_note —
  // то, что нельзя вывести из таблицы цен (что именно двигает бюджет, где
  // внутри страны дорого и почему, чего не ждут переезжающие).
