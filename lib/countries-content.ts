  intro: string;
  climate: string;
  mentality: string;
  language_note: string;
  visa_note: string;
  difficulty_overall: number; // 1-5
  hero_gradient: string; // Tailwind from-... via-... to-...
  // Этап 2 — расширенные блоки страницы страны (опциональные: секция
  // рендерится только если поле заполнено, старые записи не ломаются).
  taxes_note?: string; // налоги: подоходный, для удаленщиков/нерезидентов
  residency_note?: string; // путь к ВНЖ/ПМЖ/гражданству
