async function insertOne(slug) {
  const sb = mkClient(); // новый клиент для каждой статьи
  const d = DATA[slug];
  const { data: existing, error: se } = await sb.from('blog_posts').select('id').eq('slug', slug).maybeSingle();
  if (se) { console.error('[SELECT_ERR]', slug, se.message); return; }
  if (existing) { console.log('[SKIP]', slug); return; }
  const { error } = await sb.from('blog_posts').insert({
    slug, title: d.title, seo_title: d.seo_title, seo_description: d.seo_description,
    tag: d.tag, read_time: d.read_time, country_slug: d.country_slug, content_md: d.content_md,
    cover_url: null, cover_author_name: null, cover_author_url: null, published: true,
  });
  if (error) { console.error('[ERR]', slug, error.message); }
  else { console.log('[OK]', slug); }
}

async function run() {
  for (const slug of slugs) {
    await insertOne(slug);
    await new Promise(r => setTimeout(r, 1000));
  }
  console.log('done');
}
