const TEST_SLUGS = ["bodrum", "copenhagen"];

const isAll = process.argv.includes("--all");
const targetSlugs = isAll ? Object.keys(CITIES) : TEST_SLUGS;

async function existingItemNames(cityId) {
  const rows = await withRetry(`CHECK ${cityId}`, () =>
    fetchWithTimeout(
      `${SB_URL}/rest/v1/prices?city_id=eq.${cityId}&category=eq.rent&select=item_name_ru`,
      { headers },
    ),
  );
  return new Set((rows ?? []).map((r) => r.item_name_ru));
}

async function insertRow(cityId, name, min, max) {
  return withRetry(`INSERT ${name}`, () =>
    fetchWithTimeout(
      `${SB_URL}/rest/v1/prices`,
      {
        method: "POST",
        headers: { ...headers, Prefer: "return=minimal" },
        body: JSON.stringify({
          city_id: cityId,
          category: "rent",
          item_name_ru: name,
          price_min: min,
          price_max: max,
          is_premium: false,
          updated_at: new Date().toISOString(),
        }),
      },
      20000,
    ),
  );
}

async function run() {
  console.log(
    `=== Добавление +15 позиций rent (партия 5) — ${isAll ? "ВСЕ " + targetSlugs.length + " городов" : "ТЕСТ, " + targetSlugs.length + " города"} ===\n`,
  );

  let totalOk = 0,
    totalSkipped = 0,
    totalFail = 0;

  for (const slug of targetSlugs) {
    const city = CITIES[slug];
    if (!city) {
      console.error(`✗ ${slug}: нет данных в CITIES, пропуск`);
      continue;
    }
    console.log(`--- ${slug} (${city.city_id}) ---`);
    const existing = await existingItemNames(city.city_id);
    let ok = 0,
      skipped = 0,
      fail = 0;

    for (const [name, min, max, source] of city.items) {
      if (existing.has(name)) {
        console.log(`  - "${name}" уже есть, пропуск`);
        skipped++;
        continue;
      }
      try {
        await insertRow(city.city_id, name, min, max);
        console.log(`  ✓ ${name}: ${min}-${max} ₽ — ${source}`);
        ok++;
      } catch (e) {
        console.error(`  ✗ ${name}: не удалось — ${e.message}`);
        fail++;
      }
      await new Promise((r) => setTimeout(r, 350));
    }
    console.log(`  Итого по ${slug}: добавлено ${ok}, пропущено ${skipped}, ошибок ${fail}\n`);
    totalOk += ok;
    totalSkipped += skipped;
    totalFail += fail;
  }

  console.log(
    `\nГотово. Всего добавлено: ${totalOk}, пропущено (уже было): ${totalSkipped}, проблемных: ${totalFail}.`,
  );
  if (!isAll) {
    console.log(
      `Это был тестовый прогон (${targetSlugs.join(", ")}). Проверь результат, затем запусти:\n  node scripts/fix-rent-detail-15cities-batch5.mjs --all`,
    );
  }
}

run();
