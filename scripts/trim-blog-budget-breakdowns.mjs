// "Быстрый ответ" — исключаем отдельно: после condenseCategoryTablesInQuickAnswer
// в этой секции остаётся ровно один сводный диапазон на человека/пару/семью
// (в т.ч. продублированный в местной валюте) — это разрешённый "один общий
// диапазон на статью", а не построчная роспись по категориям, поэтому
// findDensePriceParagraphs не должен считать его задачей на ручную правку.
// Доп. категории, которые по итогам ручной разметки 2026-09-29 (batches 1-6,
// ~50 постов) последовательно НЕ трогаем — они не дублируют платный пакет
// «Расходы» (аренда/продукты/транспорт/ЖКХ-связь), это другие темы:
// медицина/страховка (не входит в 4 базовые категории пакета), "сколько
// нужно зарабатывать" (доход, не расход), образование (отдельная тема для
