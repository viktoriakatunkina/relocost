function trimDlyaPereezdaPost(content) {
  const changedSections = [];
  const lines = content.split("\n");
  const out = [];
  let i = 0;
  let templateIdx = 0;
  let currentCity = null;
  while (i < lines.length) {
    const line = lines[i];
    const h3Match = line.match(/^###\s+(.+)$/);
    if (h3Match) {
      const foundCity = Object.keys(DLYA_PEREEZDA_CITY_SLUGS).find((c) => h3Match[1].includes(c));
      if (foundCity) currentCity = foundCity;
    }
    if (/^\|.*Стартовые расходы.*\|.*Сумма.*\|/.test(line)) {
      // Нашли начало целевой таблицы — собираем её целиком.
      const tableLines = [line];
      let j = i + 1;
      while (j < lines.length && /^\|/.test(lines[j])) {
        tableLines.push(lines[j]);
        j++;
      }
      changedSections.push({ heading: `(таблица «Стартовые расходы» — ${currentCity || "?"})`, before: tableLines.join("\n") });
      const cityInfo = DLYA_PEREEZDA_CITY_SLUGS[currentCity] || { slug: "tbilisi", genitive: "Тбилиси" };
      const template = DLYA_PEREEZDA_CTA_TEMPLATES[templateIdx % DLYA_PEREEZDA_CTA_TEMPLATES.length];
      templateIdx++;
      out.push(template(cityInfo.genitive, cityInfo.slug));
      i = j;
      continue;
    }
    out.push(line);
    i++;
  }
  return { newContent: out.join("\n"), changedSections };
}

