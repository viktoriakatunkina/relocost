// Слова рядом со ссылкой, которые обычно означают "это сравнение с ДРУГИМ
// городом", а не собственная ссылка статьи — такие кандидаты не берём.
const COMPARISON_CONTEXT_RE = /дороже|дешевле|сравн|присмотреться|заметно|в отличие|аналог|с другими|против\s/i;
// А эти слова рядом со ссылкой, наоборот, почти всегда означают "это ссылка
// на СВОЙ ЖЕ город статьи" (профиль/калькулятор города) — даём таким
// кандидатам приоритет даже при более низкой частоте упоминания.
const SELF_REF_CONTEXT_RE = /калькулятор|профиль/i;

// Заполняется в main() из таблицы cities (slug -> name_ru, именительный
// падеж) — так название города в CTA всегда грамматически корректно, вне
// зависимости от того, в каком падеже оно стояло в исходном тексте ссылки
// ("в Стамбуле", "калькуляторе Аделаиды" и т.п.).
let CITY_NAME_BY_SLUG = new Map();

// Точечный фолбэк для постов, где во всём content_md вообще нет ни одной
// /city/-ссылки (проверено: 1 пост из 106 — trailand-обзор трёх городов).
const NO_CITY_LINK_FALLBACK_SLUG = {
  "stoimost-zhizni-v-tailande-2026": "bangkok",
};
let currentPostSlug = null;

function extractCityAndPrice(content, sectionStart = 0) {
  // Ловим и относительные ссылки (/city/slug), и абсолютные
  // (https://relocost.ru/city/slug) — в паре постов встречается второй вариант.
  const allCityLinks = [...content.matchAll(/\[([^\]]+)\]\([^)]*\/city\/([a-z0-9-]+)\)/g)];
  const candidates = allCityLinks.map((m) => {
    // Окно пошире — фразы вида "Для прямого сравнения со столицей — X и Y"
    // могут отстоять от самой ссылки-города дальше, чем на 40 символов.
    const before = content.slice(Math.max(0, m.index - 80), m.index);
    const linkText = m[1];
    const isComparison = COMPARISON_CONTEXT_RE.test(before);
    const isSelfRef = SELF_REF_CONTEXT_RE.test(before) || SELF_REF_CONTEXT_RE.test(linkText);
    return { slug: m[2], index: m.index, isComparison, isSelfRef };
  });
  const selfRef = candidates.filter((c) => c.isSelfRef && !c.isComparison);
  const clean = candidates.filter((c) => !c.isComparison);
  // Ссылки на "свой" город статьи (рядом "калькулятор"/"профиль") приоритетнее
  // случайных сравнений с другими городами, даже если тех больше по частоте.
  const finalPool = selfRef.length > 0 ? selfRef : clean.length > 0 ? clean : candidates;

  let citySlug = null;
  if (finalPool.length > 0) {
    // Основной критерий — частота (город, который статья реально разбирает,
    // упоминается заметно чаще случайных сравнений); близость к секции —
    // только тай-брейк при равной частоте.
    const freq = new Map();
    for (const c of finalPool) freq.set(c.slug, (freq.get(c.slug) || 0) + 1);
    finalPool.sort((a, b) => {
      const byFreq = freq.get(b.slug) - freq.get(a.slug);
      if (byFreq !== 0) return byFreq;
      return Math.abs(a.index - sectionStart) - Math.abs(b.index - sectionStart);
    });
    citySlug = finalPool[0].slug;
  } else if (currentPostSlug && NO_CITY_LINK_FALLBACK_SLUG[currentPostSlug]) {
    citySlug = NO_CITY_LINK_FALLBACK_SLUG[currentPostSlug];
  }
  const cityName = citySlug ? CITY_NAME_BY_SLUG.get(citySlug) || null : null;

  // Ищем уже существующее упоминание цены рядом с "разовый платеж" — чтобы
  // не выдумывать цифру, а переиспользовать то, что уже есть в статье.
  const priceLineMatch = content.match(/(\d{2,4})\s?₽[^.\n]*?разов(?:ый|ой)\s*плат[её]ж/i)
    || content.match(/разов(?:ый|ой)\s*плат[её]ж[^.\n]*?(\d{2,4})\s?₽/i)
    || content.match(/пакет[^.\n]*?(\d{2,4})\s?₽/i);
  const price = priceLineMatch ? priceLineMatch[1] : null;

  return { cityName, citySlug, price };
}

