function buildCtaParagraph(content, sectionStart = 0) {
  const { cityName, citySlug, price } = extractCityAndPrice(content, sectionStart);
  const priceText = price
    ? `${price} ₽, разовый платёж, доступ остаётся навсегда`
    : "разовый платёж без подписки, доступ остаётся навсегда";
  const place = citySlug
    ? `Relocost по городу [${cityName || citySlug}](/city/${citySlug})`
    : "Relocost"; // не нашли ни одной /city/-ссылки в статье — крайний случай
  const template = CTA_TEMPLATES[ctaTemplateCounter % CTA_TEMPLATES.length];
  ctaTemplateCounter++;
  return template(place, priceText);
}

function parseHeadings(content) {
  const re = /^(#{2,3})[ \t]+(.+)$/gm;
  const out = [];
  let m;
  while ((m = re.exec(content)) !== null) {
    out.push({ level: m[1].length, text: m[2].trim(), full: m[0], index: m.index });
  }
  return out;
}

function tableCellsOf(line) {
  return line.split("|").map((c) => c.replace(/\*/g, "").trim()).filter(Boolean);
}

// Транспонированная таблица (Podgorica-style): строки — это уровни/сценарии
// бюджета, а КАТЕГОРИИ расходов — это колонки, с колонкой "Итого" в конце.
// Пример: | Уровень | Аренда | Еда | Транспорт | Прочее | Итого/мес |
// Оставляем только колонку с названием уровня и колонку "Итого".
function tryExtractTransposedTotals(tableLines) {
  const header = tableCellsOf(tableLines[0]);
  if (header.length < 3) return null;
  const totalColIdx = header.findIndex((c, idx) => idx > 0 && /Итого|Всего|Бюджет/i.test(c));
  if (totalColIdx === -1) return null;
  const categoryColsCount = header.filter((c, idx) => idx > 0 && idx !== totalColIdx && CATEGORY_ROW_RE.test(`| ${c}`)).length;
  if (categoryColsCount < 2) return null; // не похоже на разбивку по категориям
  const dataRows = tableLines.slice(2); // после шапки и строки-разделителя
  const out = [];
  for (const row of dataRows) {
    const cells = tableCellsOf(row);
    if (cells.length <= totalColIdx) continue;
    out.push(`**${cells[0]}:** ${cells[totalColIdx]}`);
  }
  return out;
}

// Обрабатывает ТЕЛО одной целевой секции: сохраняет H3/H4-подзаголовки,
// итоговые/총-строки (таблицы и буллеты), качественные описания и
// нераспознанные (не по категориям) таблицы; убирает только построчную
// разбивку по категориям расходов. Возвращает removed=false, если убирать
// было нечего — тогда секцию вообще не трогаем (защита от ложных
// срабатываний вроде заголовков "разбор по категориям", где по факту нет
// сводной таблицы с итого).
function condenseSectionBody(body) {
  const lines = body.split("\n");
  const out = [];
  let removed = false;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];

    if (/^#{3,4}\s+/.test(line)) {
      out.push(line);
      i++;
      continue;
    }

    if (/^\|/.test(line)) {
      const tableLines = [line];
      let j = i + 1;
      while (j < lines.length && /^\|/.test(lines[j])) {
        tableLines.push(lines[j]);
        j++;
      }
      const hasTotal = tableLines.some((l) => TOTAL_ROW_RE.test(l));
      const hasCategoryRows = tableLines.some((l) => CATEGORY_ROW_RE.test(l));
      const transposed = !hasTotal && !hasCategoryRows ? tryExtractTransposedTotals(tableLines) : null;
      if (hasTotal) {
        const headerCells = tableCellsOf(tableLines[0]);
        const totalLines = tableLines.filter((l) => TOTAL_ROW_RE.test(l));
        for (const tl of totalLines) {
          const [label, ...values] = tableCellsOf(tl);
          // Если колонка значения ровно одна — не дублируем её заголовок
          // ("**Итого:** Сумма: 100 ₽" читается коряво), просто пишем цифру.
          const labeled = values.length === 1
            ? values[0]
            : values.map((v, idx) => (headerCells[idx + 1] ? `${headerCells[idx + 1]}: ${v}` : v)).join(", ");
          out.push(`**${label}:** ${labeled}`);
        }
        removed = true;
      } else if (hasCategoryRows) {
        removed = true; // чистая табл. по категориям без итого — убираем целиком
        // Заодно убираем осиротевшую подпись-атрибуцию сразу после таблицы
        // (она ссылалась именно на удалённые цифры — без таблицы не имеет смысла).
        let k = j;
        while (k < lines.length && lines[k].trim() === "") k++;
        if (k < lines.length && ORPHAN_CAPTION_RE.test(lines[k])) {
          j = k + 1;
        }
      } else if (transposed) {
        out.push(...transposed);
        removed = true;
      } else {
        out.push(...tableLines); // нераспознанная/референсная таблица — не трогаем
      }
      i = j;
      continue;
    }

    if (/^[-*]\s/.test(line)) {
      const bulletLines = [line];
      let j = i + 1;
      while (j < lines.length && /^[-*]\s/.test(lines[j])) {
        bulletLines.push(lines[j]);
        j++;
      }
      const totalBullets = bulletLines.filter((l) => TOTAL_BULLET_RE.test(l));
      const categoryBullets = bulletLines.filter((l) => CATEGORY_BULLET_RE.test(l));
      if (totalBullets.length > 0) {
        out.push(...totalBullets);
        removed = true;
      } else if (categoryBullets.length >= Math.ceil(bulletLines.length / 2)) {
        removed = true; // весь список — по категориям, без итого — убираем
      } else {
        out.push(...bulletLines);
      }
      i = j;
      continue;
    }

    // Обычный абзац: если в нём ≥2 инлайн-цен в скобках вида "($200)" —
    // это прозаическая разбивка по категориям (см. stoimost-zhizni-v-tbilisi),
    // убираем только сами цифры, текст и структуру предложения оставляем.
    const inlineMatches = line.match(INLINE_PRICE_PAREN_RE);
    if (inlineMatches && inlineMatches.length >= 2) {
      out.push(line.replace(INLINE_PRICE_PAREN_RE, ""));
      removed = true;
    } else {
      out.push(line);
    }
    i++;
  }
  return { newBody: out.join("\n"), removed };
}

// Возвращает { newContent, changedSections: [{heading, before}] }
function trimGenericPost(content) {
  ctaTemplateCounter = 0; // каждая статья начинает ротацию формулировок заново
  const headings = parseHeadings(content);
  const changedSections = [];
  let result = "";
  let cursor = 0;

  for (let i = 0; i < headings.length; i++) {
    const h = headings[i];
    if (!matchesTarget(h.text)) continue;

    // Конец секции — начало следующего заголовка уровня <= текущему.
    let end = content.length;
    for (let j = i + 1; j < headings.length; j++) {
      if (headings[j].level <= h.level) {
        end = headings[j].index;
        break;
      }
    }
    const sectionStart = h.index;
    const bodyStart = h.index + h.full.length;
    const before = content.slice(sectionStart, end);
    const body = content.slice(bodyStart, end);

    const { newBody, removed } = forceFullWipe(h.text)
      ? { newBody: "", removed: true }
      : condenseSectionBody(body);
    if (!removed) continue; // ложное срабатывание по названию заголовка — не трогаем

    // Копируем всё до этой секции как есть.
    result += content.slice(cursor, sectionStart);
    const cta = buildCtaParagraph(content, sectionStart);
    result += `${h.full}\n${newBody.replace(/\n{3,}/g, "\n\n").replace(/\s+$/, "")}\n\n${cta}\n\n`;
    cursor = end;
    changedSections.push({ heading: h.text, before: before.trim() });
  }
  result += content.slice(cursor);
  return { newContent: result, changedSections };
}

