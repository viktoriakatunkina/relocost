// Отчёт для dry-run: ищем H2-секции (кроме виза/ошибки/FAQ/чек-лист/итоги —
// см. EXCLUDE_HEADING_FOR_PROSE_RE), где остался абзац прозы с 2+ ценами —
// т.е. секции, ещё НЕ покрытые MANUAL_SECTION_REWRITES. Не применяется
// автоматически, только печатается как список задач.
function findDensePriceParagraphs(content) {
  const headings = parseHeadings(content);
  const out = [];
  for (let i = 0; i < headings.length; i++) {
    const h = headings[i];
    if (h.level > 2) continue;
    if (EXCLUDE_HEADING_FOR_PROSE_RE.test(h.text)) continue;
    let end = content.length;
    for (let j = i + 1; j < headings.length; j++) {
      if (headings[j].level <= h.level) { end = headings[j].index; break; }
    }
    const body = content.slice(h.index + h.full.length, end);
    const blocks = body.split(/\n{2,}/);
    for (const block of blocks) {
      const trimmed = block.trim();
      if (!trimmed) continue;
      // Картинки/HTML-комментарии/голые H3-подзаголовки без текста — не
      // абзац прозы, пропускаем. ВАЖНО: раньше сюда же попадали и
      // таблицы/буллеты ("|"/"-" в начале строки) — из-за этого построчная
      // роспись цен ПОД ПРОИЗВОЛЬНЫМ заголовком (не из TARGET_HEADING_PATTERNS,
      // а значит никогда не проходящим через condenseSectionBody) вообще не
      // засчитывалась. Живой пример: stoimost-zhizni-v-bishkeke-2026, секция
      // "Аренда жилья: сколько стоит квартира" — таблица "Цены по районам" с
      // 4 районами × 3 типами жилья ни разу не попадала в отчёт. Теперь
      // таблицы/буллеты тоже считаем — пропускаем только чистые
      // картинки/комментарии и заголовки без соседнего текста.
      if (/^(?:!\[|<!--)/.test(trimmed)) continue;
      if (/^#{3,4}\s+\S+$/.test(trimmed) && !trimmed.includes("\n")) continue; // голый H3/H4 без текста в этом же блоке
      const matches = trimmed.match(PRICE_MENTION_RE) || [];
      if (matches.length >= 2) {
        out.push({ heading: h.text, count: matches.length, preview: trimmed.slice(0, 90).replace(/\n/g, " ") });
      }
    }
  }
  return out;
}

// То же самое, но для ответов в FAQ-секции — отдельный проход, т.к. FAQ
// исключена из findDensePriceParagraphs (её обрабатывает
// MANUAL_FAQ_REWRITES, а не MANUAL_SECTION_REWRITES).
function findDenseFaqAnswers(content) {
  // ВАЖНО: "$" внутри регэкспа с флагом /m ловит конец КАЖДОЙ строки (не
  // конец всей строки content) — из-за ленивого "[\s\S]*?" это раньше
  // обрубало захват группы 2 до пустой строки сразу после заголовка FAQ, и
  // findDenseFaqAnswers молча никогда ничего не находил (проверено: 0 из 106
  // при реально существующих плотных FAQ-ответах). "(?![\s\S])" — настоящий
  // конец строки, не зависящий от /m.
  const m = content.match(/^#{2,3}[ \t]+(Часто задаваемые вопросы|FAQ)[^\n]*\n([\s\S]*?)(?=\n#{1,3}[ \t]|\n---|(?![\s\S]))/im);
  if (!m) return [];
  const pairs = [...m[2].matchAll(/\*\*(.+?)\*\*\n([^\n]+(?:\n(?!\*\*)[^\n]+)*)/g)];
  const out = [];
  for (const p of pairs) {
    const matches = p[2].match(PRICE_MENTION_RE) || [];
    if (matches.length >= 2) out.push({ question: p[1].trim(), count: matches.length });
  }
  return out;
}

// Доп. проход: в норме "## Быстрый ответ..." даёт ИТОГО по составу семьи
// (1 человек/пара/семья) без разбивки по категориям — такое мы не трогаем.
// Но в паре постов (аудит нашёл минимум 1: stoimost-zhizni-v-afinah-2026)
// сама таблица "Быстрый ответ" устроена наоборот — строки это КАТЕГОРИИ
// (Аренда/Продукты/Транспорт...) с финальной строкой "Итого". Это тот же
// самый "итог по всем категориям", просто в другом месте статьи. Ищем такие
// таблицы по сигнатуре строк-категорий и оставляем только Итого-строку(и).
// Кириллица не поддерживает \b в JS-regex — вместо него после ключевого
// слова требуем "не продолжение кириллического слова" через negative
// lookahead: так "Аренда" не поймает "Арендатор", а "Бюджет" не поймает
// "Бюджетный", но нормально поймает "Аренда:", "Аренда —", "Аренда 1-комн.".
const NOT_CYRILLIC_CONTINUATION = "(?![а-яёА-ЯЁ])";
const CATEGORY_WORDS = "Аренда|Продукты|Транспорт|Коммуналка|ЖКХ|Связь|Кафе|Депозит|Легализация|Виза|Обустройство|Страховка|Коммунальные|Жиль[её]|Вилла|Квартира|Комната|Питание|Еда|Развлечения|Медицина|Здоровье|Прочее|Мотобайк|Скутер|Спортзал|Фитнес|Непредвиденное|Резерв|Буфер|Рестораны?|Одежда|Агент";
const CATEGORY_ROW_RE = new RegExp(`^\\|\\s*\\**\\s*(${CATEGORY_WORDS})${NOT_CYRILLIC_CONTINUATION}`, "i");
const CATEGORY_BULLET_RE = new RegExp(`^[-*]\\s*\\**\\s*(${CATEGORY_WORDS})${NOT_CYRILLIC_CONTINUATION}`, "i");
const TOTAL_WORDS = "Итого|Всего|Бюджет на одного|Бюджет\\/мес|Полный бюджет|Бюджет";
const TOTAL_ROW_RE = new RegExp(`^\\|\\s*\\**\\s*(${TOTAL_WORDS})${NOT_CYRILLIC_CONTINUATION}`, "i");
const TOTAL_BULLET_RE = new RegExp(`^[-*]\\s*\\**\\s*(${TOTAL_WORDS})${NOT_CYRILLIC_CONTINUATION}`, "i");
// Инлайн-цифры в прозе вида "продукты ($120)" или "($200)" — убираем сами
// скобки с числом, оставляя качественное описание без точной цифры.
const INLINE_PRICE_PAREN_RE = /\s?\((?:USD|EUR|€|₽|\$)\s?[\d][\d\s,.]*\)|\s?\([\d][\d\s,.]*\s?(?:USD|EUR|€|₽|\$)\)/gi;

// Короткая подпись-атрибуция вида "Цифры — из данных калькулятора Relocost
// по <город> на 2026 год." — идёт сразу после таблицы "Ключевые цифры"/
// "Быстрый ответ" и ссылается именно на неё. Если саму таблицу целиком
// вырезаем (см. condenseSectionBody), эта строка осиротевает и ссылается в
// никуда — вырезаем её вместе с таблицей.
const ORPHAN_CAPTION_RE = /^\*?Цифры\s*(—|-)/i;

// Считаем "плотность" цен. Ловит и "19 000–33 000 ₽", и "$2 700", и "€1 250",
// а также цены, записанные СЛОВОМ валюты вместо символа — "700-1 100 евро",
// "87 сомов" и т.п. (аудит 2026-09-29 нашёл минимум 2 живых случая —
// stoimost-zhizni-v-nice-2026 и stoimost-zhizni-v-bishkeke-2026 — где вся
// секция была написана в евро/сомах словом и потому НИ РАЗУ не попадала в
// отчёт до этого фикса). "(?![а-яёА-ЯЁ])" вместо "\b" — see NOT_CYRILLIC_CONTINUATION
// чуть ниже по файлу, тот же самый паттерн для кириллицы, определён здесь же
// т.к. используется раньше своего места объявления ниже (используем строкой).
// Плюс трёхбуквенные коды валют (USD/EUR/THB/AED/CHF/PLN/CZK и т.п.) —
// аудит 2026-09-29 нашёл посты (Афины, Прага, Таиланд, Тбилиси-районы — по
// 40-70+ пропущенных упоминаний в каждом), где ВСЕ цены записаны через код
// валюты вместо символа/слова, и поэтому ни разу не попадали в отчёт до
// этого фикса.
const PRICE_MENTION_RE = /(?:\$|€)\s?\d[\d\s]{1,7}(?:\s?(?:–|-)\s?\d[\d\s]{1,7})?|\d[\d\s]{1,7}(?:\s?(?:–|-)\s?\d[\d\s]{1,7})?\s?(?:₽|\$|€)|\d[\d\s]{0,7}(?:\s?(?:–|-)\s?\d[\d\s]{0,7})?\s?(?:евро|доллар[а-я]*|фунт[а-я]*|бат[а-я]*|сом[а-я]*|лир[а-я]*|дирхам[а-я]*|рупи[а-я]*|юан[а-я]*|вон[а-я]*|песо|злот[а-я]*|крон[а-я]*|динар[а-я]*)(?![а-яёА-ЯЁ])|\d[\d\s]{0,7}(?:\s?(?:–|-)\s?\d[\d\s]{0,7})?\s?(?:USD|EUR|GBP|CZK|PLN|THB|AED|CHF|CAD|AUD|NT\$|HKD|ZAR|MAD|NIS|IDR|CNY|RON|SGD)\+?/gi;

// H2-секции, где цены по-прежнему уместны и НЕ считаются "give-away" —
// виза/легализация (в этой партии статей их явно просили не трогать),
// типичные ошибки (единичные иллюстративные цифры, не построчная роспись),
// FAQ (обрабатывается отдельным проходом), чек-лист, читайте также/полезные
