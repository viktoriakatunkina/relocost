// дублирует пакет ИМЕННО этого города), подводные камни/частые вопросы —
// синонимы уже исключённых "типичные ошибки"/FAQ с другой формулировкой.
// "Перел[ёе]т" (билет до города — не входит в 4 базовые категории платного
// пакета «Расходы»: аренда/продукты/транспорт/ЖКХ-связь), Golden Visa/NHR/
