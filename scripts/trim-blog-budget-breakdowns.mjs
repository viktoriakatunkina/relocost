// Применяет MANUAL_SECTION_REWRITES[slug] — заменяет ТЕЛО секции (заголовок
// не трогаем) на заранее отредактированный текст. Идём с конца документа к
// началу, чтобы индексы более ранних заголовков не съезжали от правок.
function applyManualSectionRewrites(content, slug) {
  const map = MANUAL_SECTION_REWRITES[slug];
  if (!map) return { newContent: content, changedSections: [] };
  const changedSections = [];
  let result = content;
  const headings = parseHeadings(result);
  for (let i = headings.length - 1; i >= 0; i--) {
    const h = headings[i];
    const key = h.text.trim();
    if (!(key in map)) continue;
    let end = result.length;
    for (let j = i + 1; j < headings.length; j++) {
      if (headings[j].level <= h.level) { end = headings[j].index; break; }
    }
    const bodyStart = h.index + h.full.length;
    const before = result.slice(h.index, end).trim();
    const newBody = `\n\n${map[key].trim()}\n\n`;
    result = result.slice(0, bodyStart) + newBody + result.slice(end);
    changedSections.push({ heading: h.text, before });
  }
  return { newContent: result, changedSections };
}

// Применяет MANUAL_FAQ_REWRITES[slug] — заменяет ответ (и, опционально,
// вопрос) на конкретный Q/A-блок в FAQ-секции по точному тексту вопроса.
function applyManualFaqRewrites(content, slug) {
  const entries = MANUAL_FAQ_REWRITES[slug];
  if (!entries) return { newContent: content, changedSections: [] };
  let result = content;
  const changedSections = [];
  for (const entry of entries) {
    const escaped = entry.question.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(`\\*\\*${escaped}\\*\\*\\n([^\\n]+(?:\\n(?!\\*\\*)[^\\n]+)*)`);
    const m = result.match(re);
    if (!m) continue; // вопрос не найден дословно — не трогаем, не гадаем
    const before = m[0];
    const newQ = entry.newQuestion || entry.question;
    const replacement = `**${newQ}**\n${entry.newAnswer.trim()}`;
    result = result.slice(0, m.index) + replacement + result.slice(m.index + m[0].length);
    changedSections.push({ heading: `FAQ: ${entry.question}`, before });
  }
  return { newContent: result, changedSections };
}

