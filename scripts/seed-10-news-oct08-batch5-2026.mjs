const usedSlugs = new Set();
function uniqueSlug(title) {
  const base = slugify(title);
  let slug = base;
  let i = 2;
  while (usedSlugs.has(slug)) {
    slug = `${base}-${i}`;
    i++;
  }
  usedSlugs.add(slug);
  return slug;
}

async function main() {
  let added = 0,
    skipped = 0;

  for (let i = 0; i < NEWS.length; i++) {
    const n = NEWS[i];
    const slug = uniqueSlug(n.title);

    if (LIVE) {
      const existsRes = await fetchWithRetry(
        `${SB_URL}/rest/v1/news_items?slug=eq.${slug}&select=id`,
        { headers },
      );
      const existing = await existsRes.json();
      if (existing.length) {
        console.log(`skip (уже есть): ${slug}`);
        skipped++;
        continue;
      }
    }

    const row = {
      title: n.title,
      slug,
      summary: n.summary,
      content_md: n.content_md,
      category: n.category,
      source_name: n.source_name ?? null,
      source_url: n.source_url ?? null,
      event_date: n.event_date,
      published: true,
    };

    if (!LIVE) {
      console.log(`[dry] + ${slug} | ${n.category} | ${n.event_date} | «${n.title}»`);
      added++;
      continue;
    }

    await fetchWithRetry(`${SB_URL}/rest/v1/news_items`, {
      method: "POST",
      headers,
      body: JSON.stringify(row),
    });
    console.log(`+ ${slug} (${n.category}, ${n.event_date})`);
    added++;
    await sleep(300);
  }

  console.log(`\ndone. added=${added} skipped=${skipped} / total=${NEWS.length}`);
}

await main();
