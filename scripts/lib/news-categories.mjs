// Allow-list категорий для news_items.category.
//
// Добавлено 2026-10-29 (ночной автономный аудит, задача
// #news-off-topic-content): на эту дату 84% опубликованных новостей
// (106 из 126) оказались НЕ релокационной тематикой — генерик мировые
// новости (Технологии/Наука/Спорт/Культура/Политика/Война/Климат/
// Происшествия/региональные дайджесты и т.п.), которые семантически не
// относятся к продукту (калькулятор бюджета переезда). Реально про переезд/
// визы/недвижимость было только 20 из 126 (категории «Визы», «Иммиграция»,
// «Недвижимость»).
//
// Раздел /news задумывался как мостик к продукту («новость → посчитайте
// бюджет переезда»), а не как генерик новостной агрегатор — несвязанный
// контент размывает тематическое ядро сайта и не ведёт к конверсии.
//
// ЛЮБОЙ новый seed-скрипт для news_items (scripts/seed-*-news-*.mjs или его
// преемник) должен импортировать assertAllowedCategory() и вызывать её для
// КАЖДОЙ новости перед записью в Supabase — чтобы новые статьи не плодили
// off-topic контент дальше. Уже опубликованные 106 off-topic статей этим
// файлом не затрагиваются — их судьба (unpublish/рекатегоризация) отдельное
// решение Виктории, не автоматизация.
//
// Список — осознанно консервативный. Если нужна новая категория, сначала
// убедиться, что она прямо про переезд/жизнь в новой стране, а не про
// мировые новости "around the topic" (пример границы: статистика покупки
// жилья иностранцами — да, «Недвижимость»; общая макроэкономика страны —
// нет).
export const ALLOWED_NEWS_CATEGORIES = Object.freeze([
  "Визы",
  "Иммиграция",
  "Недвижимость",
]);

/**
 * Бросает исключение, если category не входит в ALLOWED_NEWS_CATEGORIES.
 * Вызывать для каждого элемента перед записью в news_items (сразу после
 * формирования объекта новости, до POST в Supabase).
 *
 * @param {string} category
 * @param {string} [context] — например, заголовок новости, для понятного сообщения об ошибке.
 */
export function assertAllowedCategory(category, context = "") {
  if (!ALLOWED_NEWS_CATEGORIES.includes(category)) {
    const where = context ? ` (${context})` : "";
    throw new Error(
      `news_items.category "${category}"${where} не входит в allow-list ` +
        `релокационных тем: ${ALLOWED_NEWS_CATEGORIES.join(", ")}. ` +
        `Раздел /news — мостик к продукту, не генерик новостной агрегатор. ` +
        `См. scripts/lib/news-categories.mjs.`,
    );
  }
}
