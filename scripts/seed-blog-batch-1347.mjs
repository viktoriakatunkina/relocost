async function insertOne(p) {
  const sb = mkSb();
  const { data: ex, error: se } = await sb.from('blog_posts').select('id').eq('slug', p.slug).maybeSingle();
  if (se) { console.error('[SELECT_ERR]', p.slug, se.message.substring(0,80)); return; }
  if (ex) { console.log('[SKIP]', p.slug); return; }
  const { error } = await sb.from('blog_posts').insert({
    slug: p.slug, title: p.title, seo_title: p.seo_title, seo_description: p.seo_description,
    tag: p.tag, read_time: p.read_time, country_slug: p.country_slug, content_md: p.content_md,
    cover_url: null, cover_author_name: null, cover_author_url: null, published: true,
  });
  if (error) { console.error('[ERR]', p.slug, error.message.substring(0,80)); }
  else { console.log('[OK]', p.slug); }
}

