function buildPriceRows(slug, cityId) {
  const d = DATA[slug];
  const rows = [];

  FIXED_ITEMS.cafe.forEach(([name, premium], i) => {
    const [min, max] = d.cafe[i];
    rows.push({ city_id: cityId, category: "cafe", item_name_ru: name, price_min: min, price_max: max, is_premium: premium });
  });
  FIXED_ITEMS.entertainment.forEach(([name, premium], i) => {
    const [min, max] = d.entertainment[i];
    rows.push({ city_id: cityId, category: "entertainment", item_name_ru: name, price_min: min, price_max: max, is_premium: premium });
  });
  FIXED_ITEMS.food.forEach(([name, premium], i) => {
    const [min, max] = d.food[i];
    rows.push({ city_id: cityId, category: "food", item_name_ru: name, price_min: min, price_max: max, is_premium: premium });
  });
  FIXED_ITEMS.health.forEach(([name, premium], i) => {
    const [min, max] = d.health[i];
    rows.push({ city_id: cityId, category: "health", item_name_ru: name, price_min: min, price_max: max, is_premium: premium });
  });
  d.utilities.forEach(([name, premium], i) => {
    const [min, max] = d.utilitiesPrices[i];
    rows.push({ city_id: cityId, category: "utilities", item_name_ru: name, price_min: min, price_max: max, is_premium: premium });
  });
  TRANSPORT_ITEMS.forEach(([name, premium], i) => {
    const [min, max] = d.transport[i];
    rows.push({ city_id: cityId, category: "transport", item_name_ru: name, price_min: min, price_max: max, is_premium: premium });
  });
  RENT_BASE.forEach((name, i) => {
    const [min, max] = d.rentBase[i];
    rows.push({ city_id: cityId, category: "rent", item_name_ru: name, price_min: min, price_max: max, is_premium: false });
  });
  d.rentDistrict.forEach(([name, min, max]) => {
    rows.push({ city_id: cityId, category: "rent", item_name_ru: name, price_min: min, price_max: max, is_premium: false });
  });

  return rows;
}

async function run() {
  console.log(`Seed 2 новых городов (Асунсьон, Маврикий) стартует... (${new Date().toLocaleString("ru")})\n`);
  let addedCities = 0, addedPrices = 0;

  for (const c of CITIES) {
    const { data: existing } = await sb.from("cities").select("id").eq("slug", c.slug).maybeSingle();
    if (existing) {
      console.log(`  SKIP (уже есть в cities): ${c.slug}`);
      continue;
    }

    const prep = PREPOSITIONAL[c.slug] ?? `в ${c.name_ru}`;
    const seo_title = `Стоимость жизни ${prep} в ${YEAR} году — калькулятор | Relocost`;
    const seo_description = `Сколько стоит жить ${prep}? Аренда, еда, транспорт — реальный бюджет на месяц. Калькулятор, цены, визы, отзывы.`;

    const row = {
      name_ru: c.name_ru, name_en: c.name_en, slug: c.slug,
      country_ru: c.country_ru, country_en: c.country_en, country_slug: c.country_slug,
      flag_emoji: c.flag_emoji, population: c.population, climate: c.climate,
      language: c.language, currency: c.currency, flight_from_moscow: c.flight_from_moscow,
      is_foreign: c.is_foreign, difficulty_score: c.difficulty_score, is_popular: c.is_popular,
      seo_title, seo_description, intro_text: c.intro_text, lat: c.lat, lng: c.lng,
    };

    const { data: inserted, error: cityErr } = await sb
      .from("cities").insert(row).select("id").single();
    if (cityErr) { console.error(`  ОШИБКА города ${c.slug}: ${cityErr.message}`); continue; }

    const cityId = inserted.id;
    console.log(`[+] ${c.name_ru} (${c.slug}) -> ${cityId}`);
    addedCities++;

    const priceRows = buildPriceRows(c.slug, cityId);
    const { error: pErr } = await sb.from("prices").insert(priceRows);
    if (pErr) { console.error(`  ОШИБКА цен ${c.slug}: ${pErr.message}`); }
    else { console.log(`  цены: ${priceRows.length} записей`); addedPrices += priceRows.length; }
  }

  console.log("\n" + "=".repeat(50));
  console.log(`Городов добавлено: ${addedCities}/2`);
  console.log(`Записей цен добавлено: ${addedPrices}`);
  console.log("=".repeat(50));
}

run().catch((e) => {
  console.error("КРИТИЧЕСКАЯ ОШИБКА:", e.message);
  process.exit(1);
});
