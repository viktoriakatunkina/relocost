async function run() {
  console.log(`=== +15 позиций rent для 8 новых городов (23-я волна) — ${new Date().toLocaleString("ru")} ===\n`);
  let totalOk = 0, totalSkipped = 0, totalFail = 0;

  for (const [slug, city] of Object.entries(CITIES)) {
    const { data: cityRow, error: cErr } = await sb.from("cities").select("id").eq("slug", slug).maybeSingle();
    if (cErr || !cityRow) { console.error(`  ОШИБКА поиска города ${slug}: ${cErr?.message ?? "не найден"}`); continue; }
    console.log(`--- ${slug} (${cityRow.id}) ---`);

    const { data: existing, error: exErr } = await sb
      .from("prices")
      .select("item_name_ru")
      .eq("city_id", cityRow.id)
      .eq("category", "rent");
    if (exErr) { console.error(`  ОШИБКА чтения существующих: ${exErr.message}`); continue; }
    const existingNames = new Set((existing ?? []).map((r) => r.item_name_ru));

    let ok = 0, skipped = 0, fail = 0;
    for (const [name, min, max] of city.items) {
      if (existingNames.has(name)) {
        console.log(`  - "${name}" уже есть, пропуск`);
        skipped++;
        continue;
      }
      const { error: insErr } = await sb.from("prices").insert({
        city_id: cityRow.id, category: "rent", item_name_ru: name,
        price_min: min, price_max: max, is_premium: false,
      });
      if (insErr) { console.error(`  ✗ ${name}: ${insErr.message}`); fail++; }
      else { console.log(`  ✓ ${name}: ${min}-${max}`); ok++; }
    }
    totalOk += ok; totalSkipped += skipped; totalFail += fail;
    console.log(`  итог ${slug}: +${ok} новых, ~${skipped} пропущено, ${fail} ошибок\n`);
  }

  console.log("=== ИТОГ ===");
  console.log(`Добавлено: ${totalOk}, пропущено: ${totalSkipped}, ошибок: ${totalFail}`);
}

run().catch((e) => {
  console.error("FATAL:", e);
  process.exit(1);
});
