// Маппинг slug → city_id (заполняется из БД)
const SLUGS = Object.keys(PRICES);

async function main() {
  // 1. Получаем city_id
  const { data: cities, error: cityErr } = await sb
    .from("cities")
    .select("id, slug")
    .in("slug", SLUGS);
  if (cityErr) throw cityErr;

  const bySlug = new Map(cities.map((c) => [c.slug, c.id]));

  let totalInserted = 0;
  let totalUpdated = 0;
  let totalSkipped = 0;
  const results = [];

  for (const slug of SLUGS) {
    const cityId = bySlug.get(slug);
    if (!cityId) {
      console.error(`SKIP ${slug}: город не найден в cities`);
      results.push({ slug, status: "not_found" });
      continue;
    }

    // Получаем уже существующие item_name_ru для этого города
    const { data: existing, error: fetchErr } = await sb
      .from("prices")
      .select("id, item_name_ru")
      .eq("city_id", cityId);
    if (fetchErr) {
      console.error(`ERROR ${slug}: fetch — ${fetchErr.message}`);
      results.push({ slug, status: "error", detail: fetchErr.message });
      continue;
    }

    const existingMap = new Map(existing.map((r) => [r.item_name_ru, r.id]));

    let inserted = 0;
    let updated = 0;

    for (let i = 0; i < ITEMS.length; i++) {
      const [category, item_name_ru, is_premium] = ITEMS[i];
      const [price_min, price_max] = PRICES[slug][i];
      const existingId = existingMap.get(item_name_ru);

      // Округляем до целых (price_min/price_max — integer в БД)
      const pMin = Math.round(price_min);
      const pMax = Math.round(price_max);

      if (existingId) {
        // Обновляем существующую запись
        const { error: updErr } = await sb
          .from("prices")
          .update({ price_min: pMin, price_max: pMax, category, is_premium, updated_at: new Date().toISOString() })
          .eq("id", existingId);
        if (updErr) {
          console.error(`  UPDATE error ${slug}/${item_name_ru}: ${updErr.message}`);
        } else {
          updated++;
        }
      } else {
        // Вставляем новую запись
        const { error: insErr } = await sb.from("prices").insert({
          city_id: cityId,
          category,
          item_name_ru,
          price_min: pMin,
          price_max: pMax,
          is_premium,
        });
        if (insErr) {
          console.error(`  INSERT error ${slug}/${item_name_ru}: ${insErr.message}`);
        } else {
          inserted++;
        }
      }
    }

    totalInserted += inserted;
    totalUpdated += updated;
    results.push({ slug, inserted, updated, total: existing.length });
    console.log(
      `  ${slug}: +${inserted} новых, ~${updated} обновлено (было ${existing.length} строк)`
    );
  }

  console.log("\n=== ИТОГ ===");
  console.log(`Городов обработано: ${results.filter(r => r.status !== "not_found" && r.status !== "error").length}/${SLUGS.length}`);
  console.log(`Новых строк добавлено: ${totalInserted}`);
  console.log(`Строк обновлено: ${totalUpdated}`);
  console.log("\nСписок городов:");
  results
    .filter(r => r.status !== "not_found" && r.status !== "error")
    .forEach(r => console.log(`  ${r.slug}: +${r.inserted} новых, ~${r.updated} обновлено`));
}

main().catch((e) => {
  console.error("FATAL:", e);
  process.exit(1);
});
