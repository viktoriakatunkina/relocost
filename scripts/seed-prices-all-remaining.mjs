// Получаем все города
const { data: cities } = await sb.from("cities").select("id,slug").limit(200);
const bySlug = new Map(cities.map(c => [c.slug, c.id]));

// Узнаем, у каких уже есть цены
const { data: existing } = await sb.from("prices").select("city_id").limit(2000);
const hasPrices = new Set(existing.map(r => r.city_id));

let totalInserted = 0, totalSkipped = 0, totalErrors = 0;

for (const [slug, priceArr] of Object.entries(PRICES)) {
  const cityId = bySlug.get(slug);
  if (!cityId) {
    console.warn(`! Город не найден: ${slug}`);
    totalSkipped++;
    continue;
  }
  if (hasPrices.has(cityId)) {
    console.log(`~ ${slug}: уже есть цены, пропуск`);
    totalSkipped++;
    continue;
  }

  const rows = ITEMS.map(([category, item_name_ru, is_premium], i) => ({
    city_id: cityId,
    category,
    item_name_ru,
    price_min: Math.max(1, Math.round(priceArr[i][0])),
    price_max: Math.max(1, Math.round(priceArr[i][1])),
    is_premium,
  }));

  const { error } = await sb.from("prices").insert(rows);
  if (error) {
    console.error(`✗ ${slug}: ${error.message}`);
    totalErrors++;
  } else {
    console.log(`✓ ${slug} (${rows.length} строк)`);
    totalInserted += rows.length;
  }
}

console.log(`\nИтого: вставлено ${totalInserted} строк, пропущено ${totalSkipped}, ошибок ${totalErrors}`);
