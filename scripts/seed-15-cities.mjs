async function fetchUnsplash(query) {
  const u = new URL("https://api.unsplash.com/search/photos");
  u.searchParams.set("query", query);
  u.searchParams.set("per_page", "5");
  u.searchParams.set("orientation", "landscape");
  const res = await fetch(u, { headers: { Authorization: `Client-ID ${UNSPLASH}` } });
  if (!res.ok) throw new Error(`Unsplash ${query}: ${res.status}`);
  const json = await res.json();
  const pick = json.results?.[0];
  if (!pick) return null;
  return {
    photo_id: pick.id,
    base_url: pick.urls.raw,
    author_name: pick.user.name,
    author_url: pick.user.links.html,
  };
}

async function run() {
  console.log("Seed 15 городов стартует...\n");
  let added = 0;
  let skipped = 0;

  for (const c of CITIES) {
    const { data: existing } = await sb.from("cities").select("id").eq("slug", c.slug).maybeSingle();
    if (existing) {
      console.log(`skip (exists): ${c.slug}`);
      skipped++;
      continue;
    }

    let photo = null;
    try {
      photo = await fetchUnsplash(c.unsplash_query);
    } catch (e) {
      console.warn(`  unsplash failed for ${c.slug}: ${e.message}`);
    }

    const row = {
      name_ru: c.name_ru,
      name_en: c.name_en,
      slug: c.slug,
      country_ru: c.country_ru,
      country_en: c.country_en,
      country_slug: c.country_slug,
      flag_emoji: c.flag_emoji,
      population: c.population,
      climate: c.climate,
      language: c.language,
      currency: c.currency,
      flight_from_moscow: c.flight_from_moscow,
      is_foreign: c.is_foreign,
      difficulty_score: c.difficulty_score,
      is_popular: c.is_popular,
      seo_title: c.seo_title,
      seo_description: c.seo_description,
      intro_text: c.intro_text,
      lat: c.lat,
      lng: c.lng,
      unsplash_photo_id: photo?.photo_id ?? null,
      unsplash_url: photo?.base_url ?? null,
      unsplash_author_name: photo?.author_name ?? null,
      unsplash_author_url: photo?.author_url ?? null,
    };

    const { data: inserted, error } = await sb.from("cities").insert(row).select("id").single();
    if (error) throw new Error(`insert city ${c.slug}: ${error.message}`);
    const cityId = inserted.id;

    const pricesData = (PRICES[c.slug] || []).map(([cat, item, min, max, prem]) => ({
      city_id: cityId,
      category: cat,
      item_name_ru: item,
      price_min: min,
      price_max: max,
      is_premium: prem,
    }));

    if (pricesData.length) {
      const { error: pErr } = await sb.from("prices").insert(pricesData);
      if (pErr) throw new Error(`insert prices ${c.slug}: ${pErr.message}`);
    }

    console.log(`+ ${c.name_ru} (${c.slug}): ${pricesData.length} позиций цен${photo ? " + фото" : " (без фото)"}`);
    added++;
  }

  console.log(`\nГотово: добавлено ${added} городов, пропущено ${skipped}.`);
}

run().catch((e) => {
  console.error("ОШИБКА:", e.message);
  process.exit(1);
});
